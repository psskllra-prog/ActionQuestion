@contextmanager
def keep_typing(chat_id):
    stop_event = threading.Event()

    def _loop():
        while not stop_event.is_set():
            try:
                bot.send_chat_action(chat_id, "typing")
            except Exception:
                pass
            stop_event.wait(4)

    thread = threading.Thread(target=_loop, daemon=True)
    thread.start()
    try:
        yield
    finally:
        stop_event.set()
        thread.join(timeout=1)

def get_feedback_keyboard(with_points=True):
    keyboard = types.InlineKeyboardMarkup(row_width=6)
    btn_yes = types.InlineKeyboardButton(text="Помогло", callback_data="help_yes")
    btn_no = types.InlineKeyboardButton(text="Не помогло", callback_data="help_no")
