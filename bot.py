@bot.callback_query_handler(func=lambda call: call.data in ["help_yes", "help_no"])
def handle_feedback(call):
    global last_client_id
    user_id = call.message.chat.id
    msg_id = call.message.message_id

    if msg_id in answered_feedbacks:
        bot.answer_callback_query(call.id, text="Вы уже выбрали действие для этого ответа.")
        return

    answered_feedbacks.add(msg_id)
    bot.answer_callback_query(call.id)

    try:
        bot.edit_message_reply_markup(chat_id=user_id, message_id=msg_id, reply_markup=None)
    except Exception:
        pass

    if call.data == "help_yes":
        failed_attempts[user_id] = 0
        last_ai_response.pop(user_id, None)
        bot.send_message(
            user_id,
            "Рады были помочь! Пожалуйста, оцените работу бота по 5-балльной шкале:",
            reply_markup=get_rating_keyboard()
        )

    elif call.data == "help_no":
        last_ai_response.pop(user_id, None)
        failed_attempts[user_id] = failed_attempts.get(user_id, 0) + 1
        count = failed_attempts[user_id]
        print(f"Попыток 'не помогло' для {user_id}: {count}")

        if count >= 2:
            operator_active[user_id] = True
            last_client_id = user_id
            bot.send_message(user_id, "В ближайшие время с вами свяжется специалист")
            alert = bot.send_message(
                OPERATOR_CHAT_ID,
                f"Клиент {user_id} переведен на оператора!\nОтветьте через Reply на это сообщение."
            )
            msg_to_client[alert.message_id] = user_id
        else:
            bot.send_message(user_id, "Пожалуйста, опишите проблему подробнее, для того чтобы мы могли эффективно разобраться")

