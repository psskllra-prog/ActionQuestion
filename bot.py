def generate_with_gemini_rotation(prompt: str):
    global current_key_index
    attempts = len(ai_clients)

    for _ in range(attempts):
        with key_lock:
            client = ai_clients[current_key_index]
            idx = current_key_index

        try:
            response = client.models.generate_content(
                model="gemini-3.6-flash",
                contents=prompt
            )
            return response.text
        except Exception as e:
            err_str = str(e).lower()
            print(f"[Ключ #{idx}] Ошибка: {e}")

            retry_triggers = [
                "429", "503", "504", "quota", "exhausted",
                "deadline", "timeout", "unavailable", "resource_exhausted"
            ]

            if any(trigger in err_str for trigger in retry_triggers):
                with key_lock:
                    current_key_index = (current_key_index + 1) % len(ai_clients)
                    print(f"-> Переключаемся на ключ #{current_key_index}...")
                time.sleep(1)
                continue
            else:
                with key_lock:
                    current_key_index = (current_key_index + 1) % len(ai_clients)
                continue

    raise RuntimeError("Все доступные API-ключи Gemini исчерпали свой суточный лимит!")

